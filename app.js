function login(event) {
  event.preventDefault();
  const username = document.querySelector("#loginUsername").value.trim();
  const password = document.querySelector("#loginPassword").value;
  const employee = state.employees.find((item) => item.username === username && item.password === password);

  if (!employee) {
    alert("Неверный логин или пароль.");
    return;
  }

  state.sessionEmployeeId = employee.id;
  state.activeEmployeeId = employee.isAdmin ? visibleEmployees()[0]?.id || employee.id : employee.id;
  event.target.reset();
  persistAndRender();
}

