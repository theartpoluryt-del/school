function migrateOrchestraGroup(data) {
  const normalize = (value) => String(value || "").trim().toLocaleLowerCase("ru-RU");
  const teacher = data.employees.find((employee) => normalize(employee.name).includes("полуротова"));
  if (!teacher) return;

  const oldStudent = data.students.find((student) => normalize(student.name) === "оркестр");
  let group = data.groups.find((item) => normalize(item.name) === "оркестр");
  if (!group) {
    group = {
      id: crypto.randomUUID(),
      externalId: nextGroupExternalIdFor(data),
      name: "Оркестр",
      className: "оркестр",
      studentIds: [],
      assignedEmployeeIds: [teacher.id]
    };
    data.groups.push(group);
  }

  group.className = group.className || "оркестр";
  group.studentIds = group.studentIds || [];
  group.assignedEmployeeIds = uniqueByIdValues([...(group.assignedEmployeeIds || []), teacher.id]);

  if (oldStudent) {
    data.schedule.forEach((row) => {
      if (row.studentId === oldStudent.id) {
        row.studentId = group.id;
        row.className = group.className;
        row.type = "Оркестр";
      }
    });
    data.records.forEach((record) => {
      if (record.studentId === oldStudent.id) {
        record.studentId = group.id;
        record.studentName = group.name;
        record.className = group.className;
        record.type = "Оркестр";
      }
    });
    data.students = data.students.filter((student) => student.id !== oldStudent.id);
  }
}

function nextGroupExternalIdFor(data) {
  const number = Math.max(0, ...(data.groups || []).map((group) => Number(String(group.externalId || "").replace(/\D/g, "")) || 0)) + 1;
  return `G-${String(number).padStart(4, "0")}`;
}

