function applyContingentSeed(data) {
  if (!Array.isArray(contingentSeed) || !contingentSeed.length) return data;

  const normalize = (value) => String(value || "").trim().toLocaleLowerCase("ru-RU").replace(/\s+/g, " ");
  const studentKey = (student) => normalize(student.name);
  const teacherByName = new Map(data.employees.map((employee) => [normalize(employee.name), employee]));
  const studentByKey = new Map(data.students.map((student) => [studentKey(student), student]));
  let studentNumber = Math.max(0, ...data.students.map((student) => Number(String(student.externalId || "").replace(/\D/g, "")) || 0));
  const usedUsernames = new Set(data.employees.map((employee) => employee.username).filter(Boolean));

  const nextRosterStudentId = () => {
    studentNumber += 1;
    return `S-${String(studentNumber).padStart(4, "0")}`;
  };

  const usernameForTeacher = (name, index) => {
    const lowerName = normalize(name);
    if (lowerName.includes("полуротова")) return "teacher";
    if (lowerName.includes("иванова")) return "ivanova";
    let candidate = `teacher${String(index + 1).padStart(3, "0")}`;
    let suffix = index + 1;
    while (usedUsernames.has(candidate)) {
      suffix += 1;
      candidate = `teacher${String(suffix).padStart(3, "0")}`;
    }
    usedUsernames.add(candidate);
    return candidate;
  };

  contingentSeed.forEach((teacherSeed, teacherIndex) => {
    const teacherName = String(teacherSeed.teacher || "").trim();
    if (!teacherName) return;

    const lowerTeacherName = normalize(teacherName);
    let employee = teacherByName.get(lowerTeacherName);
    if (!employee && lowerTeacherName.includes("полуротова")) {
      employee = data.employees.find((item) => item.username === "teacher");
    }
    if (!employee && lowerTeacherName.includes("иванова")) {
      employee = data.employees.find((item) => item.username === "ivanova");
    }
    if (employee) {
      employee.name = teacherName;
      teacherByName.set(lowerTeacherName, employee);
    }
    if (!employee) {
      employee = {
        id: crypto.randomUUID(),
        name: teacherName,
        role: teacherSeed.subject || "Преподаватель",
        username: usernameForTeacher(teacherName, teacherIndex),
        password: "teacher123",
        isAdmin: false
      };
      data.employees.push(employee);
      teacherByName.set(normalize(teacherName), employee);
    } else {
      employee.role = (!employee.role || employee.role === "Преподаватель") ? (teacherSeed.subject || "Преподаватель") : employee.role;
      employee.username = employee.username || usernameForTeacher(teacherName, teacherIndex);
      employee.password = employee.password || "teacher123";
      employee.isAdmin = Boolean(employee.isAdmin);
    }

    (teacherSeed.students || []).forEach((studentSeed) => {
      const candidate = {
        name: String(studentSeed.name || "").trim(),
        className: String(studentSeed.className || "").trim()
      };
      if (!candidate.name) return;

      let student = studentByKey.get(studentKey(candidate));
      if (!student) {
        student = {
          id: crypto.randomUUID(),
          externalId: nextRosterStudentId(),
          name: candidate.name,
          className: candidate.className,
          educationForm: "ДПП",
          assignedEmployeeIds: []
        };
        data.students.push(student);
        studentByKey.set(studentKey(student), student);
      } else if (candidate.className && !String(student.className || "").includes("/")) {
        student.className = candidate.className;
      }

      student.assignedEmployeeIds = student.assignedEmployeeIds || [];
      if (!student.assignedEmployeeIds.includes(employee.id)) student.assignedEmployeeIds.push(employee.id);
    });
  });

  mergeDuplicateStudentsByName(data);
  data.contingentSeedVersion = "may-2026-v2-full-roster";
  return data;
}

function mergeDuplicateStudentsByName(data) {
  const byName = new Map();
  const replacements = new Map();
  data.students = data.students.filter((student) => {
    const key = String(student.name || "").trim().toLocaleLowerCase("ru-RU").replace(/\s+/g, " ");
    if (!key) return false;
    const existing = byName.get(key);
    if (!existing) {
      byName.set(key, student);
      return true;
    }
    if (!String(existing.className || "").includes("/") && student.className) existing.className = student.className;
    existing.assignedEmployeeIds = uniqueByIdValues([...(existing.assignedEmployeeIds || []), ...(student.assignedEmployeeIds || [])]);
    replacements.set(student.id, existing.id);
    return false;
  });
  data.groups.forEach((group) => {
    group.studentIds = uniqueByIdValues((group.studentIds || []).map((id) => replacements.get(id) || id));
  });
  data.schedule.forEach((row) => {
    row.studentId = replacements.get(row.studentId) || row.studentId;
    const student = data.students.find((item) => item.id === row.studentId);
    if (student && !String(row.className || "").includes("/")) row.className = student.className;
  });
  data.records.forEach((record) => {
    record.studentId = replacements.get(record.studentId) || record.studentId;
    const student = data.students.find((item) => item.id === record.studentId);
    if (student && !String(record.className || "").includes("/")) record.className = student.className;
  });
}

function uniqueByIdValues(values) {
  return [...new Set(values.filter(Boolean))];
}

